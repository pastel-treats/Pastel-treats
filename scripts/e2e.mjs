// End-to-end walk-through on a phone-sized screen (demo mode). Saves screenshots to ./shots
import { chromium } from 'playwright'
import { mkdirSync } from 'node:fs'
const BASE = process.env.BASE || 'http://localhost:4173'
const OUT = process.env.OUT || 'shots'
mkdirSync(OUT, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROME || undefined, headless: false, args: ['--headless=new'] })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
page.on('console', (m) => m.type() === 'error' && !/fonts\.g|ERR_NAME|net::/.test(m.text()) && errors.push('console: ' + m.text()))
const shot = (n, full = false) => page.screenshot({ path: `${OUT}/${n}.png`, fullPage: full })
const log = (...a) => console.log('•', ...a)
const wait = (ms) => page.waitForTimeout(ms)

